#!/usr/bin/env node
/**
 * 生成 dsh 0.2.x 的 agent preset 声明块（0.1.x 的目录扫描已被
 * `@deepseek-ai/dsh-agent-preset-registry` 取代：preset 只能由 profile patch 里的
 * `@deepseek-ai/dsh-agent-preset` 声明行提供，`~/.dsh/.agent-presets/<id>/` 不再被读取）。
 *
 * 数据源 = 本仓库 `presets/<id>/{preset.yml,agent.cordis.yml}`（与 gen-client-presets.mjs 同源）：
 *   preset.yml        → id / name / description / order
 *   agent.cordis.yml  → 逐行搬运为声明行的 `plugins:` 列表（跳过 `---` 文档分隔符，缩进 10 空格）
 *
 * 产物 = 写进目标 profile patch（默认 `~/.dsh/profiles/web/cordis.patch.yml`）的
 * 标记块 `# ══ dsh:preset-registry BEGIN/END ══`，可重复执行（幂等，改完重跑即可）。
 *
 * 用法：node scripts/gen-preset-registry.mjs [--patch <file>] [--presets <dir>]
 *          [--default <id>] [--stdout] [--check]
 *   --stdout  只打印块内容，不写文件
 *   --check   只校验 patch 里的块与生成结果一致（回归用）
 */
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'

const repo = path.resolve(import.meta.dirname, '..')
const argv = process.argv.slice(2)
function opt(name, fallback) {
  const i = argv.indexOf(name)
  return i >= 0 && argv[i + 1] !== undefined ? argv[i + 1] : fallback
}
const PRESETS_DIR = path.resolve(opt('--presets', path.join(repo, 'presets')))
const PATCH = path.resolve(opt('--patch', path.join(os.homedir(), '.dsh', 'profiles', 'web', 'cordis.patch.yml')))
const DEFAULT_PRESET = opt('--default', 'harmony-chat')
const STDOUT_ONLY = argv.includes('--stdout')
const CHECK_ONLY = argv.includes('--check')

const BEGIN = '# ══ dsh:preset-registry BEGIN (generated by scripts/gen-preset-registry.mjs) ══'
const END = '# ══ dsh:preset-registry END ══'
const INDENT = ' '.repeat(10)
const pluginsRow = ' '.repeat(8)

/** 取 yml 顶层标量（只看行首不缩进的那一行）。 */
function topScalar(text, key) {
  const m = new RegExp(`^${key}:\\s*(.*)$`, 'm').exec(text)
  if (m === null) return ''
  const v = m[1].trim()
  if (v.length >= 2 && ((v.startsWith("'") && v.endsWith("'")) || (v.startsWith('"') && v.endsWith('"')))) {
    return v.slice(1, -1)
  }
  return v
}

function block() {
  const ids = fs.readdirSync(PRESETS_DIR, { withFileTypes: true })
    .filter((d) => d.isDirectory()).map((d) => d.name)
    .sort((a, b) => a.localeCompare(b))
  const out = [
    BEGIN,
    `# 0.2.x 迁移：preset 只能由声明行提供（0.1.x 的目录扫描 ${'~'}/.dsh/.agent-presets/<id>/ 已失效）。`,
    '# 本块 = 仓库 presets/ 的逐字节搬运；改预设后重跑 scripts/gen-preset-registry.mjs（或 dsh-hm-update.mjs）。',
    '- id: agent-preset-registry',
    '  config:',
    `    default: ${DEFAULT_PRESET}`,
  ]
  let n = 0
  for (const id of ids) {
    const dir = path.join(PRESETS_DIR, id)
    const metaPath = path.join(dir, 'preset.yml')
    const bodyPath = path.join(dir, 'agent.cordis.yml')
    if (!fs.existsSync(bodyPath)) continue
    const meta = fs.existsSync(metaPath) ? fs.readFileSync(metaPath, 'utf8') : ''
    const body = fs.readFileSync(bodyPath, 'utf8')
      .split('\n').filter((l) => l.trim() !== '---').join('\n').replace(/\s+$/, '')
    out.push('')
    out.push('- insert:')
    out.push(`    - id: preset-${id}`)
    out.push("      name: '@deepseek-ai/dsh-agent-preset'")
    out.push('      config:')
    out.push(`        id: ${id}`)
    const name = topScalar(meta, 'name')
    const description = topScalar(meta, 'description')
    const order = topScalar(meta, 'order')
    if (name) out.push(`        name: ${JSON.stringify(name)}`)
    if (description) out.push(`        description: ${JSON.stringify(description)}`)
    if (order) out.push(`        order: ${order}`)
    out.push('        plugins:')
    out.push(body.split('\n').map((l) => (l.length ? INDENT + l : l)).join('\n'))
    n++
  }
  out.push(END)
  out.push('')
  return { text: out.join('\n'), count: n }
}

const { text, count } = block()

if (STDOUT_ONLY) {
  process.stdout.write(text)
} else if (CHECK_ONLY) {
  const current = fs.existsSync(PATCH) ? fs.readFileSync(PATCH, 'utf8') : ''
  const b = current.indexOf(BEGIN)
  const e = current.indexOf(END)
  const have = b >= 0 && e > b ? current.slice(b, e + END.length) + '\n' : ''
  if (have !== text) {
    console.error(`[gen-preset-registry] 与 ${PATCH} 不一致（块缺失或已过期）`)
    process.exitCode = 1
  } else {
    console.log(`[gen-preset-registry] 校验通过：${count} 套预设 → ${PATCH}`)
  }
} else {
  const current = fs.existsSync(PATCH) ? fs.readFileSync(PATCH, 'utf8') : ''
  const b = current.indexOf(BEGIN)
  const e = current.indexOf(END)
  let next
  if (b >= 0 && e > b) {
    next = current.slice(0, b) + text + current.slice(e + END.length).replace(/^\n+/, '\n')
    if (!next.endsWith('\n')) next += '\n'
  } else {
    next = current.replace(/\s*$/, '') + '\n\n' + text
  }
  if (next !== current) {
    if (fs.existsSync(PATCH)) {
      const bak = `${PATCH}.bak-${new Date().toISOString().replace(/[:.]/g, '-').slice(0, 19)}-preset-registry`
      fs.copyFileSync(PATCH, bak)
      console.log(`[gen-preset-registry] 已备份 → ${bak}`)
    } else {
      const dir = path.dirname(PATCH)
      if (!fs.existsSync(dir)) {
        console.error(`[gen-preset-registry] 目标 profile 不存在，未写入：${dir}`)
        process.exit(1)
      }
    }
    fs.writeFileSync(PATCH, next)
    console.log(`[gen-preset-registry] 已写入 ${count} 套预设声明 → ${PATCH}`)
  } else {
    console.log(`[gen-preset-registry] 已是最新（${count} 套预设）→ ${PATCH}`)
  }
}
